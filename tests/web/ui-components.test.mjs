// Семантика компонентов и сохранность реальных примеров контента. Без браузерных зависимостей.
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { runInNewContext } from 'node:vm'
const appRequire = createRequire(new URL('../../apps/web/package.json', import.meta.url))
const { transpileModule, ModuleKind, JsxEmit } = appRequire('typescript')
const { createElement: h } = appRequire('react')
const { renderToStaticMarkup: render } = appRequire('react-dom/server')
const base = new URL('../../apps/web/src/ui/', import.meta.url)
const cache = new Map()
function load(name) {
  if (cache.has(name)) return cache.get(name)
  const exports = {}
  const text = readFileSync(new URL(name, base), 'utf8')
  const { outputText } = transpileModule(text, { compilerOptions: { module: ModuleKind.CommonJS, jsx: JsxEmit.ReactJSX, target: 9 } })
  runInNewContext(outputText, { exports, Intl, Date, require: id => id === './copy' ? load('copy.ts') : appRequire(id) })
  cache.set(name, exports)
  return exports
}
const ui = load('components.tsx')
const html = (Component, props, ...children) => render(h(Component, props, ...children))
const field = html(ui.Field, { label: 'Название', hint: 'До 60 знаков', error: 'Введите название' })
const id = field.match(/<label for="([^"]+)"/)[1]
assert.ok(field.includes(`id="${id}"`))
assert.ok(field.includes('aria-invalid="true"'))
assert.ok(field.includes(`aria-describedby="${id}-hint ${id}-error"`))
assert.ok(field.includes(`id="${id}-error"`))
assert.ok(html(ui.Button, { disabled: true }, 'Добавить').includes('type="button"'))
assert.ok(html(ui.FilterChip, { selected: true }, 'Дома').includes('aria-pressed="true"'))
const segments = html(ui.Segmented, { label: 'Вид', value: 'city', options: [{ value: 'home', label: 'Дома' }, { value: 'city', label: 'В городе' }], onChange() {} })
assert.ok(segments.includes('role="radiogroup"'))
assert.equal((segments.match(/tabindex="0"/g) ?? []).length, 1)
assert.ok(segments.includes('aria-checked="true"'))
const fact = (value, checkedAt, source = 'https://example.org/facts') => ({ value, checkedAt, source })
const facts = html(ui.SourceFacts, { facts: [{ label: 'Часы', fact: fact('10–18', '2026-11-16') }, { label: 'Цена', fact: fact('Тариф автора', '2026-11-10', 'owner') }] })
assert.ok(facts.includes('10 ноября 2026'))
assert.ok(!facts.includes('16 ноября 2026'))
assert.ok(facts.includes('по данным автора сайта'))
assert.ok(!facts.includes('href="owner"'))
const withAddress = html(ui.SourceFacts, { facts: [{ label: 'Часы', fact: fact('10–18', '2026-11-16') }], linkedFacts: [{ label: 'Адрес', fact: fact('Адрес', '2026-11-10', 'owner') }] })
assert.ok(withAddress.includes('10 ноября 2026'), 'дата адреса-ссылки тоже участвует в общей дате')
const unknown = html(ui.SourceFacts, { facts: [{ label: 'Часы' }, { label: 'Стоимость' }] })
assert.ok(!unknown.includes('Проверено'))
assert.ok(!unknown.includes('href='))
assert.equal((unknown.match(/Уточнить перед визитом/g) ?? []).length, 2)
const palette = html(ui.AccentPalette, { value: 'green', onChange() {} })
assert.equal((palette.match(/aria-pressed=/g) ?? []).length, 9)
assert.equal((palette.match(/aria-pressed="true"/g) ?? []).length, 1)
for (const kind of ['today', 'later', 'lead']) assert.ok(html(ui.StatusBadge, { kind }).includes('aria-hidden="true"'))
const days = [{ id: 'sat', label: 'В субботу', onAdd() {} }, { id: 'sun', label: 'В воскресенье', onAdd() {}, disabled: true }]
assert.equal((html(ui.AddToDay, { state: { kind: 'days', days } }).match(/<button/g) ?? []).length, 2)
assert.ok(html(ui.AddToDay, { state: { kind: 'partial', existing: 1, total: 3, onAdd() {} } }).includes('1 из 3 уже в плане'))
assert.ok(html(ui.AddToDay, { state: { kind: 'create-two-days', onAdd() {} } }).includes('Сделать план на два дня'))
assert.ok(html(ui.AddToDay, { state: { kind: 'two-days', onAdd() {} } }).includes('В субботу и воскресенье'))
assert.ok(html(ui.AddToDay, { state: { kind: 'added', dayLabel: 'суббота', planHref: '?view=plan' } }).includes('href="?view=plan"'))
assert.ok(html(ui.LoadError, { onRetry() {} }).includes('role="alert"'))
assert.ok(html(ui.Toast, { error: true }, 'Ошибка').includes('role="alert"'))
assert.ok(html(ui.Toast, {}, 'Добавлено').includes('role="status"'))
const film = load('preview-film.ts').previewFilm
const recipe = load('preview-recipe.ts').previewRecipe
const content = name => JSON.parse(readFileSync(new URL(`../../apps/web/src/content/${name}.json`, import.meta.url)))
assert.equal(JSON.stringify(film), JSON.stringify(content('films').find(x => x.id === film.id)), 'пример фильма должен совпадать с базой')
assert.equal(JSON.stringify(recipe), JSON.stringify(content('recipes').find(x => x.id === 'roman-pizza')), 'пример рецепта не должен менять исходник владелицы')
const recipeHtml = html(ui.RecipeBlocks, { recipe })
assert.ok(recipeHtml.includes('390'))
assert.ok(recipeHtml.includes('48–72'))
for (const section of recipe.sections) assert.ok(recipeHtml.includes(section.title))
const movie = html(ui.FilmChoice, { film, selected: true, onSelect() {} })
assert.ok(movie.includes(film.title))
assert.ok(movie.includes(film.note))
assert.ok(movie.includes('Источник описания'))
assert.ok(movie.includes('Выбран ✓'))
assert.ok(movie.includes('ws-poster-fallback'), 'без URL постера выбор фильма остаётся доступен')
console.log('Компоненты: семантика полей и выбора, даты/неизвестные факты, 9 акцентов, состояния добавления, ошибки, рецепт автора и мини-описание фильма — OK')